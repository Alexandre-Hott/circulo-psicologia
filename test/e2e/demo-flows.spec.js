test('repeated series changes remain in Agenda history through keyboard cancellation and restoration', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button',{name:/Agenda/}).click()
  await page.getByLabel('Data da agenda').fill('2026-10-06')
  await page.getByRole('button',{name:/Novo compromisso recorrente/}).click()
  const create=page.getByRole('dialog',{name:'Nova série recorrente'})
  await create.getByLabel('Paciente').selectOption({label:'Theo Almeida'})
  await create.getByRole('button',{name:'Criar série'}).click()
  await page.getByRole('button',{name:'Dia',exact:true}).click()
  const revise=async(date,start,end,reason,existing)=>{
    await page.getByRole('button',{name:new RegExp(`${existing} · Theo Almeida`)}).click()
    const edit=page.getByRole('dialog',{name:'Alterar compromisso'})
    await edit.getByLabel('Aplicar a').selectOption('Série a partir desta data')
    await edit.getByLabel('Nova data').fill(date)
    await edit.getByLabel('Início').fill(start)
    await edit.getByLabel('Fim').fill(end)
    await edit.getByLabel('Motivo da remarcação (opcional)').fill(reason)
    page.once('dialog',dialog=>dialog.accept())
    const apply=edit.getByRole('button',{name:'Remarcar série a partir desta data'})
    await apply.focus()
    await apply.press('Enter')
  }
  await revise('2026-10-07','09:00','09:50','Primeira revisão administrativa','09:00–09:50')
  await page.getByLabel('Data da agenda').fill('2026-10-07')
  await revise('2026-10-08','10:00','10:50','Segunda revisão administrativa','09:00–09:50')
  const history=page.getByRole('region',{name:'Histórico de alterações da agenda'})
  await expect(history.getByText('Theo Almeida · Série remarcada')).toHaveCount(2)
  await expect(history).toContainText('Primeira revisão administrativa')
  await expect(history).toContainText('Segunda revisão administrativa')
  await page.getByLabel('Data da agenda').fill('2026-10-08')
  await expect(page.getByRole('button',{name:/10:00–10:50 · Theo Almeida/})).toBeVisible()
  await page.getByRole('button',{name:/10:00–10:50 · Theo Almeida/}).click()
  const cancel=page.getByRole('dialog',{name:'Alterar compromisso'})
  await cancel.getByLabel('Aplicar a').selectOption('Cancelar ocorrência')
  await cancel.getByLabel('Motivo do cancelamento').fill('Cancelamento administrativo preservado')
  const confirmCancel=cancel.getByRole('button',{name:'Confirmar cancelamento'})
  await confirmCancel.focus()
  await confirmCancel.press('Enter')
  await expect(page.getByRole('button',{name:/10:00–10:50 · Theo Almeida/})).toHaveCount(0)
  const restore=history.getByRole('button',{name:/^Restaurar ocorrência — Theo Almeida/})
  page.once('dialog',dialog=>dialog.dismiss())
  await restore.focus()
  await restore.press('Enter')
  await expect(history).not.toContainText('Ocorrência restaurada')
  await expect(history).toContainText('Cancelamento administrativo preservado')
  page.once('dialog',dialog=>dialog.accept())
  await restore.press('Enter')
  await expect(page.getByRole('button',{name:/10:00–10:50 · Theo Almeida/})).toBeVisible()
  await expect(history).toContainText('Ocorrência restaurada')
  for(const reason of ['Primeira revisão administrativa','Segunda revisão administrativa','Cancelamento administrativo preservado'])await expect(history).toContainText(reason)
  await page.getByLabel('Data da agenda').fill('2026-10-05')
  await expect(page.getByRole('button',{name:/14:30–15:20 · Luna Martins/})).toBeVisible()
  await page.getByRole('button',{name:/Pacientes/}).click()
  await page.getByRole('button',{name:/Theo Almeida/}).click()
  await expect(page.locator('main')).not.toContainText('Cancelamento administrativo preservado')
  await page.getByRole('button',{name:/Voltar aos pacientes/}).click()
  await page.getByRole('button',{name:/Luna Martins/}).click()
  await expect(page.locator('main')).not.toContainText('Primeira revisão administrativa')
  await expect(page.locator('main')).not.toContainText('Segunda revisão administrativa')
})
