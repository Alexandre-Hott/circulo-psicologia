const reachSessionSummary = async (page, summary, date) => {
  await page.getByRole('button',{name:/Luna Martins/}).click()
  await page.getByRole('button',{name:/Iniciar sessão/}).click()
  if(date)await page.getByLabel('Data',{exact:true}).fill(date)
  await page.getByRole('button',{name:/Continuar/}).click()
  await page.getByRole('button',{name:'Não quero responder'}).click()
  for(let step=0;step<3;step++)await page.getByRole('button',{name:/Continuar/}).click()
  await page.getByLabel('Resumo da sessão').fill(summary)
}

const finishOpenedSession = async (page, summary) => {
  await page.getByRole('button',{name:/Continuar/}).click()
  await page.getByRole('button',{name:'Não quero responder'}).click()
  for(let step=0;step<3;step++)await page.getByRole('button',{name:/Continuar/}).click()
  await page.getByLabel('Resumo da sessão').fill(summary)
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'Finalizar sessão'}).click()
}

